import { test, expect } from '@playwright/test'

for (const width of [390, 1440]) test(`love prompt preserves controls at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.addInitScript(() => {
    localStorage.setItem('avgst:cookie-notice-dismissed', '1')
    Object.defineProperty(navigator, 'share', { value: async () => {} })
  })
  await page.route(/yandex|roistat|one2click|mail\.ru|\/api\/(?:views|consent)/, route => route.abort())
  await page.route('**/api/reactions', route => route.fulfill({ json: { likes: 3, shares: 1 } }))
  await page.goto('/catalog/barnhouse-115')
  const like = page.locator('.project-actions__btn').first()
  await expect(like).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  const before = await like.boundingBox()
  await like.click()
  const popup = page.locator('.project-love')
  await expect(popup).toBeVisible()
  await expect.poll(() => popup.locator('img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true)
  await expect(popup).toContainText('Поделись с тем, с кем вместе мечтаешь о своём доме')
  const after = await like.boundingBox()
  expect(after?.x).toBe(before?.x)
  expect(after?.y).toBe(before?.y)
  const box = await popup.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(width)
  await expect(popup.locator('.project-love__heart')).toHaveClass(/--(ink|red|yellow)/)
  await expect.poll(() => popup.evaluate(el => getComputedStyle(el).opacity)).toBe('1')
  await page.screenshot({ path: `output/like-prompt-${width}.png` })
  await page.keyboard.press('Escape')
  await expect(popup).toHaveCount(0)
  await like.click()
  await like.click()
  await expect(popup).toHaveCount(0)
})

test('failed like does not show a prompt', async ({page}) => {
  await page.route('**/api/reactions', route => route.fulfill({status:500,json:{}}))
  await page.goto('/catalog/barnhouse-115')
  await page.locator('.project-actions__btn').first().click()
  await expect(page.locator('.project-love')).toHaveCount(0)
  await expect(page.locator('.project-actions__btn').first()).toHaveAttribute('aria-pressed','false')
})
