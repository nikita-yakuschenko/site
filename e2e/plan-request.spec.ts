test('mobile sticky CTA stays within its section and all long explication rows remain reachable', async ({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto(route)
  await page.waitForFunction(() => document.documentElement.dataset.appHydrated === 'true')
  const section=page.locator('section[data-cms-block="ProjectPlans"]')
  await section.locator('dl').evaluate(dl=>{
    for(let i=0;i<30;i++){const row=document.createElement('div');row.innerHTML=`<dt>Помещение ${i+1}</dt><dd>10 м²</dd>`;dl.append(row)}
  })
  const body=section.locator('.project-plans__body'),cta=section.locator('.plan-request-entry')
  const position=await body.evaluate(node=>({top:node.getBoundingClientRect().top+scrollY,height:node.getBoundingClientRect().height}))
  for(const offset of [120,position.height/2,position.height-600]){
    await page.evaluate(y=>scrollTo({top:y,behavior:'instant'}),position.top+offset)
    const box=await cta.boundingBox()
    expect(box!.y).toBeGreaterThanOrEqual(0)
    expect(box!.y+box!.height).toBeLessThanOrEqual(844)
    await expect(cta.getByRole('button')).toBeVisible()
  }
  await page.evaluate(()=>{const notice=document.createElement('div');notice.className='cookie-banner';notice.id='brief-test-notice';notice.innerHTML='<div style="height:100px;background:white">Уведомление</div>';document.body.append(notice)})
  await expect.poll(async()=>{const button=await cta.boundingBox(),notice=await page.locator('#brief-test-notice').boundingBox();return button!.y+button!.height<=notice!.y-15}).toBe(true)
  await page.locator('#brief-test-notice').evaluate(node=>node.remove())
  const last=section.locator('dl>div').last()
  await last.scrollIntoViewIfNeeded()
  const rowBox=await last.boundingBox(),ctaBox=await cta.boundingBox()
  expect(rowBox!.y+rowBox!.height).toBeLessThanOrEqual(ctaBox!.y)
  await section.screenshot({path:'output/plan-request/long-explication-mobile.png'})
  await page.evaluate(y=>scrollTo({top:y,behavior:'instant'}),position.top+position.height+100)
  expect((await cta.boundingBox())!.y+ (await cta.boundingBox())!.height).toBeLessThan(0)
})

