import { test, expect } from '@playwright/test'
import { defaultConfigurationTemplates } from '../src/lib/catalog/configuration-content'
for (const width of [1440,390]) test(`frame cards and independent comparison at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:1000})
 await page.addInitScript(()=>window.addEventListener('message',event=>{if(event.data?.type==='avgst:configurations-ready')(window as unknown as {configurationReady:boolean}).configurationReady=true}))
 await page.goto('/cms-preview/configurations',{waitUntil:'domcontentloaded'})
 await page.waitForFunction(()=>(window as unknown as {configurationReady?:boolean}).configurationReady===true)
 await page.evaluate(templates=>window.dispatchEvent(new MessageEvent('message',{origin:'http://localhost:3001',source:window,data:{type:'avgst:preview-configurations',variant:'frame',templates}})),defaultConfigurationTemplates())
 const cards=page.locator('.project-config__tier')
 await expect(cards).toHaveCount(3)
 await expect(cards.nth(1).locator('.project-config__tier-base')).toHaveText('стартовой')
 await expect(cards.nth(2).locator('.project-config__tier-base')).toHaveText('стандартной')
 expect(await cards.nth(1).locator('.project-config__tier-base').evaluate(el=>getComputedStyle(el).color)).not.toEqual(await cards.nth(1).locator('.project-config__tier-includes-title').evaluate(el=>getComputedStyle(el).color))
 await expect(cards.nth(0)).not.toContainText('Заводская')
 await expect(cards.nth(1)).toContainText('Металлическая входная дверь')
 await page.locator('.project-config').screenshot({path:`output/frame-configurations-fixed-${width}.png`})
 await page.getByRole('button',{name:'Сравнить комплектации'}).click()
 const dialog=page.getByRole('dialog',{name:'Сравнение комплектаций'})
 await expect(dialog).toBeVisible()
 await dialog.getByRole('button',{name:'Развернуть разделы',exact:true}).click()
 await expect(dialog.locator('[data-element="insulation"]')).toHaveCount(1)
 await expect(dialog.locator('[data-element="floor"]')).toContainText('ОСП 12 мм')
 await expect(dialog).not.toContainText('Стеновые панели')
 expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
 await page.screenshot({path:`output/frame-comparison-fixed-${width}.png`})
 await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible()
})
