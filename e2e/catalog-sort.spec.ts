import { test, expect } from '@playwright/test'

test('compact catalog sort supports keyboard, links, filter reset and mobile', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/catalog')
  const cookies = page.getByRole('button', { name: 'Необходимые', exact: true })
  if (await cookies.isVisible()) await cookies.click()
  const sort = page.getByRole('combobox', { name: 'Сортировка проектов' })
  await expect(page.locator('.cfilter').getByRole('combobox', { name: 'Сортировка проектов' })).toBeVisible()
  await expect(sort).toBeVisible()
  await sort.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('option')).toHaveCount(5)
  await page.getByRole('option', { name: 'Сначала дешевле' }).click()
  await expect(page).toHaveURL(/sort=price-asc/)
  await expect(sort).toContainText('Сначала дешевле')
  await page.reload()
  await expect(sort).toContainText('Сначала дешевле')
  for (const [label, value] of [['Сначала дороже', 'price-desc'], ['Сначала компактнее', 'area-asc'], ['Сначала просторнее', 'area-desc']] as const) {
    await sort.click()
    await page.getByRole('option', { name: label }).click()
    await expect(page).toHaveURL(new RegExp(`sort=${value}`))
    await expect(sort).toContainText(label)
  }
  const input = page.getByRole('searchbox')
  await expect(page.getByRole('button', { name: 'Сбросить всё', exact: true })).toHaveCount(1)
  await expect(page.locator('.catalog__reset')).toBeVisible()
  await page.locator('.catalog__reset').click()
  await expect(page).toHaveURL(/catalog$/)
  await expect(sort).toContainText('По умолчанию')
  await sort.click()
  await page.getByRole('option', { name: 'Сначала просторнее' }).click()
  await expect(page).toHaveURL(/sort=area-desc/)
  await input.fill('Барнхаус')
  await input.press('Enter')
  await expect(page).toHaveURL(/q=.*&sort=area-desc/)
  await page.getByRole('button', { name: 'Очистить поиск' }).click()
  await expect(page).toHaveURL(/catalog\?sort=area-desc$/)
  await sort.click()
  await page.screenshot({ path: 'test-results/catalog-sort-desktop.png', fullPage: false })
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(sort).toBeHidden()
  await page.locator('.cfilter__toggle').click()
  await expect(sort).toBeVisible()
  await sort.click()
  await expect(page.getByRole('option', { name: 'По умолчанию' })).toBeVisible()
  await page.screenshot({ path: 'test-results/catalog-sort-mobile.png', fullPage: false })
  await page.getByRole('option', { name: 'По умолчанию' }).click()
  await expect(page).toHaveURL(/catalog$/)
  await page.locator('.cfilter__apply').click()
  await expect(sort).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
