import { test, expect, type APIRequestContext } from '@playwright/test'
const enabled = Boolean(process.env.CMS_UI_TEST_EMAIL && process.env.CMS_UI_TEST_PASSWORD)
test.skip(!enabled, 'Use an explicitly designated local CMS test database and staff account')
let api: APIRequestContext, eventId: number
let cookies: Awaited<ReturnType<APIRequestContext['storageState']>>['cookies'] = []
const ids: number[] = [], suffix = `ui-${Date.now()}`
test.beforeAll(async ({ playwright, baseURL }) => {
  if (!enabled) return
  expect(['localhost', '127.0.0.1']).toContain(new URL(baseURL!).hostname)
  api = await playwright.request.newContext({ baseURL, extraHTTPHeaders: { Origin: new URL(baseURL!).origin } })
  const login = await api.post('/api/users/login', { data: { email: process.env.CMS_UI_TEST_EMAIL, password: process.env.CMS_UI_TEST_PASSWORD } })
  expect(login.ok()).toBeTruthy()
  cookies = (await api.storageState()).cookies
  for (let index = 1; index <= 60; index++) {
    const response = await api.post('/api/referral-participants', { data: { name: `Участник ${suffix} ${index}`, email: `${suffix}-${index}@example.test`, code: `${suffix}-${index}`, status: index % 2 ? 'active' : 'pending' } })
    expect(response.status()).toBe(201)
    ids.push((await response.json()).doc.id)
  }
  const response = await api.post('/api/events', { data: { title: `Мероприятие ${suffix}`, slug: suffix, status: 'published', startsAt: '2099-11-14T07:00:00Z', endsAt: '2099-11-14T10:00:00Z', confirmationEmail: { subject: 'Подтверждение', html: '<p>Здравствуйте, {{name}}!</p><p>Приглашаем вас.</p>' }, programmeEmail: { subject: 'Программа', html: '<p>Программа {{event_title}}</p>' }, reminderEmail: { subject: 'Напоминание', html: '<p>Напоминание {{event_date}}</p>' } } })
  expect(response.status()).toBe(201)
  eventId = (await response.json()).doc.id
})
test.afterAll(async () => {
  if (!api) return
  for (const id of ids) await api.delete(`/api/referral-participants/${id}`)
  if (eventId) await api.delete(`/api/events/${eventId}`)
  await api.dispose()
})
test.beforeEach(async ({ context }) => { await context.addCookies(cookies) })

test('canonical participants table searches all rows and restores filters, sorting and pagination after editing', async ({ page }) => {
  await page.goto('/referral')
  const search = page.getByRole('textbox', { name: 'Поиск участников' })
  await search.fill(suffix)
  await expect(page.locator('[data-slot="table-body"] tr')).toHaveCount(10)
  await page.getByRole('combobox', { name: 'Строк на странице' }).click()
  await page.getByRole('option', { name: '20', exact: true }).click()
  await page.getByRole('button', { name: 'Статус', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Активен', exact: true }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Код: сортировать по возрастанию' }).click()
  await page.getByRole('button', { name: 'Следующая страница' }).click()
  await expect(page.locator('[data-slot="table-body"] tr')).toHaveCount(10)
  const saved = new URL(page.url()).search
  const first = page.locator('[data-slot="table-body"] a').first()
  const name = await first.innerText()
  await first.click()
  await expect(page).toHaveURL(/\/collections\/referral-participants\/\d+/)
  await page.goto('/referral')
  await expect.poll(() => new URL(page.url()).search).toBe(saved)
  await expect(search).toHaveValue(suffix)
  await expect(page.locator('[data-slot="table-body"] a').first()).toHaveText(name)
  await search.fill(`${suffix} 59`)
  await expect(page.locator('[data-slot="table-body"] tr')).toHaveCount(1)
  await expect(page.locator('[data-slot="table-body"]')).toContainText(`Участник ${suffix} 59`)
})

test('event list opens the record; visual and highlighted HTML editors preserve variables and save the same template', async ({ page }) => {
  await page.goto(`/events?q=${suffix}`)
  await expect(page.locator('[data-slot="table-body"] tr')).toHaveCount(1)
  await page.locator(`[data-slot="table-body"] a[href="/collections/events/${eventId}"]`).click()
  await page.getByRole('tab', { name: 'Письма и напоминания', exact: true }).click()
  await expect(page.locator('.doc-controls__meta')).toBeHidden()
  const workspace = await page.locator('.event-workspace').boundingBox(), main = await page.locator('.collection-edit__main').boundingBox()
  expect(workspace!.width).toBeGreaterThan(main!.width * .85)
  const scheduled = page.getByLabel('Время отправки (пусто — сразу)', { exact: true })
  expect((await scheduled.evaluate(el => getComputedStyle(el).fontFamily)).toLowerCase()).toContain('mono')
  await expect(page.getByLabel('Письмо', { exact: true })).toHaveAttribute('data-slot', 'select-trigger')
  const editor = page.getByRole('region', { name: 'Редактор писем' })
  await editor.getByLabel('Тема письма', { exact: true }).fill('Проверенная тема')
  const frame = page.frameLocator('iframe[title="Визуальный редактор письма"]')
  await expect(frame.locator('body')).toContainText('Александр')
  await frame.locator('p').last().click()
  await page.keyboard.press('End')
  await page.keyboard.insertText(' Визуальная правка')
  await editor.getByRole('tab', { name: 'HTML', exact: true }).click()
  await expect(editor.locator('.cm-content')).toContainText('{{name}}')
  await expect(editor.locator('.cm-content')).toContainText('Визуальная правка')
  await expect(editor.getByLabel('Тема письма', { exact: true })).toHaveValue('Проверенная тема')
  const source = editor.locator('.cm-content')
  await source.click(); await page.keyboard.press('Control+Home'); await page.keyboard.press('Control+A')
  await page.keyboard.insertText('<p>Обновлено {{name}}</p><script>parent.__emailPreviewXss=1</script>')
  await editor.getByRole('tab', { name: 'Визуальный', exact: true }).click()
  await expect(frame.locator('body')).toContainText('Обновлено Александр')
  expect(await page.evaluate(() => (window as unknown as { __emailPreviewXss?: number }).__emailPreviewXss)).toBeUndefined()
  const saved = page.waitForResponse(r => r.request().method() === 'PATCH' && new URL(r.url()).pathname === `/api/events/${eventId}`)
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  expect((await saved).ok()).toBeTruthy()
  const event = await (await api.get(`/api/events/${eventId}`)).json()
  expect(event.confirmationEmail.subject).toBe('Проверенная тема')
  expect(event.confirmationEmail.html).toContain('{{name}}')
  expect(event.confirmationEmail.html).not.toContain('data-email-variable')
  await editor.getByLabel('Тип письма', { exact: true }).click()
  await page.getByRole('option', { name: 'Программа и календарь', exact: true }).click()
  await expect(editor.getByLabel('Тема письма', { exact: true })).toHaveValue('Программа')
})

test('SMTP has one settings screen and account link; catalogue uses the same persisted table controls', async ({ page }) => {
  await page.goto('/settings')
  await expect(page.getByRole('heading', { name: 'Настройки', exact: true })).toBeVisible()
  await expect(page.getByLabel('Сервер SMTP', { exact: true })).toHaveCount(1)
  await page.goto('/referral')
  await page.getByRole('tab', { name: 'Настройки', exact: true }).click()
  await expect(page.getByLabel('Сервер SMTP', { exact: true })).toHaveCount(0)
  await page.goto('/account')
  await expect(page.getByRole('heading', { name: 'Настройки', exact: true })).toHaveCount(1)
  await expect(page.locator('.doc-controls__meta')).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Аккаунт', exact: true })).toHaveAttribute('data-state', 'active')
  const firstName = page.getByLabel('Имя', { exact: true })
  const originalName = await firstName.inputValue()
  await firstName.fill(`${originalName} UI`)
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Настройки аккаунта сохранены' })).toHaveCount(1)
  await firstName.fill(originalName)
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect.poll(async () => (await (await api.get('/api/users/me')).json()).user.firstName).toBe(originalName)
  await page.getByRole('tab', { name: 'CMS', exact: true }).click()
  await expect(page).toHaveURL(/\/settings$/)
  await expect(page.getByLabel('Сервер SMTP', { exact: true })).toHaveCount(1)
  await page.goto('/catalog')
  await page.getByRole('textbox', { name: 'Поиск проектов' }).fill(suffix)
  await page.getByRole('button', { name: 'Просмотры: сортировать по возрастанию' }).click()
  const saved = new URL(page.url()).search
  await page.goto('/events'); await page.goto('/catalog')
  await expect.poll(() => new URL(page.url()).search).toBe(saved)
  await expect(page.getByRole('textbox', { name: 'Поиск проектов' })).toHaveValue(suffix)
})

