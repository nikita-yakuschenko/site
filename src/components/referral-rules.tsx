/** Пункт нумерованного списка правил. */
function Item({
  n,
  children,
  rate,
  accent,
}: {
  n: number;
  children: ReactNode;
  rate?: boolean;
  accent?: boolean;
}) {
  const className = [
    "referral-rules__item",
    rate ? "referral-rules__item--rate" : "",
    accent ? "referral-rules__item--rate-accent" : "",
  ]
    .filter(Boolean)
    .join(" ");
  return (
    <li className={className}>
      <span className="referral-rules__num">{n}.</span>
      {children}
    </li>
  );
}

function Term({ title, children }: { title: string; children: ReactNode }) {
  return (
    <div className="referral-rules__term">
      <dt>{title}</dt>
      <dd>{children}</dd>
    </div>
  );
}

function Group({
  title,
  start,
  children,
}: {
  title: string;
  start?: number;
  children: ReactNode;
}) {
  return (
    <div className="referral-rules__group">
      <h3 className="referral-rules__group-title">{title}</h3>
      <ol className="referral-rules__list" start={start}>
        {children}
      </ol>
    </div>
  );
}

