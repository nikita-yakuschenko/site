/**
 * Первый абзац раздела «О проекте», собранный из полей проекта.
 *
 * Пишется программой, а не рукой, потому что это единственный текст, который
 * можно дать правдиво по всем 37 проектам сразу: в нём нет ни одного
 * утверждения, которого не было бы в данных. Остальные абзацы раздела
 * редакционные и приходят из поля about.
 */
export function aboutIntro(project: {
  area: string;
  floorsValue: number;
  bedrooms: string;
  bathrooms: string;
}): string {
  const beds = Number(project.bedrooms);
  const baths = Number(project.bathrooms);
  const storey = project.floorsValue === 1 ? "Одноэтажный" : `${project.floorsValue}-этажный`;
  const head =
    `${storey} дом ${project.area} м² ` +
    `с ${beds} ${plural(beds, "спальней", "спальнями", "спальнями")} ` +
    `и ${baths} ${plural(baths, "санузлом", "санузлами", "санузлами")}.`;
  const tail =
    project.floorsValue === 1
      ? " Всё на одном уровне, без лестниц и перепадов."
      : " Спальни отнесены на второй этаж, дневная зона остаётся внизу.";
  return head + tail;
}
