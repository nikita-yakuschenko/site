const PREP =
  /(^|[(\s])(в|во|на|с|со|к|ко|о|об|от|до|по|из|у|за|над|под|при|про|для|без|через|и|а|но|не|ни|или)\s+/gi;

export function nbspText(text: string): string {
  return text.replace(PREP, "$1$2\u00a0");
}

