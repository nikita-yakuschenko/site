const PREP =
  /(^|[(\s])(в|во|на|с|со|к|ко|о|об|от|до|по|из|у|за|над|под|при|про|для|без|через|и|а|но|не|ни|или)\s+/gi;

export function nbspText(text: string): string {
  return text.replace(PREP, "$1$2\u00a0");
}

export function footerAboutFor(_name: string): string {
  return copy.footerAbout;
}

export function projectsInSeries(n: number): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return `${n} проектов`;
  if (last === 1) return `${n} проект`;
  if (last >= 2 && last <= 4) return `${n} проекта`;
  return `${n} проектов`;
}

export function seriesTitle(
  series: "panel" | "barn" | "classic" | "modular",
): string {
  if (series === "panel") return copy.seriesPanel;
  if (series === "barn") return copy.seriesBarn;
  if (series === "classic") return copy.seriesClassic;
  return copy.seriesModular;
}
