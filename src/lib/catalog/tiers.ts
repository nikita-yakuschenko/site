import type { CatalogProject } from "./types";

/**
 * Комплектации: три уровня, а не набор галочек.
 *
 * Дом продаётся готовыми наборами — «каркас», «каркас с кровлей, окнами и
 * фасадом», «дом по проекту». Состав материалов у всех проектов один и
 * тот же: его задаёт производство, а не конкретный дом. Поэтому описания
 * лежат здесь общим списком, а от проекта берётся только цена.
 *
 * Цены пока считаются от базовой цены проекта коэффициентами, снятыми с
 * «Барнхауса 73», где известны все три: 2 422 000 / 3 683 000 / 5 214 000
 * при базовой 3 650 000. Это заглушка до настоящего прайса — числа
 * правдоподобны, но не точны.
 */
/**
 * Пункт состава.
 *
 * Состав конструкции — это перечисление слоёв, а сплошным абзацем оно не
 * читается: в «Силовом каркасе» три узла, у каждого по пять материалов с
 * размерами. Поэтому пункт разложен: короткая мысль абзацем, узлы —
 * подзаголовками, материалы — списком.
 */
export type TierDetail = {
  title: string;
  /** Одна фраза о сути пункта. */
  lead?: string;
  /** Плоский список — когда узел один. */
  items?: readonly string[];
  /** Узлы со своими списками — когда их несколько. */
  groups?: readonly { title: string; items: readonly string[] }[];
};

export type ProjectTier = {
  id: string;
  name: string;
  /** Название в винительном падеже: «что входит в стандартную». */
  nameAcc: string;
  lead: string;
  /** Множитель к базовой цене проекта. */
  factor: number;
  /** Доступна ли комплектация в ипотеку. У стартовой дома нет — банк
   *  кредитует дом, а не каркас, — и платёж для неё не показывается. */
  mortgage: boolean;
  includes: readonly string[];
  /** Пункты, которые идут подарком: перечисляются последними и помечены
   *  отдельно — иначе теряются в общем списке галочек. */
  gifts?: readonly string[];
  details: readonly TierDetail[];
};

